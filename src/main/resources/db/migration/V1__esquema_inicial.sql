-- Esquema inicial (#101, ADR-008). Es el mismo que generaba Hibernate con
-- ddl-auto: update a partir de las entidades Concierto y Usuario.
-- No edites este archivo: cualquier cambio al esquema va en una migracion
-- nueva (V2__..., V3__...).

CREATE TABLE concierto (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artista        VARCHAR(255),
    fecha          DATE,
    ciudad         VARCHAR(255),
    lugar          VARCHAR(255),
    soundcloud_url VARCHAR(255),
    fuente         VARCHAR(255),
    id_externo     VARCHAR(255),
    latitud        NUMERIC(12, 9),
    longitud       NUMERIC(12, 9),
    url_compra     VARCHAR(2048),
    imagen_url     VARCHAR(2048),
    precio_minimo  NUMERIC(12, 2),
    -- Un evento importado se identifica por su proveedor y su id en ese proveedor.
    CONSTRAINT uk_concierto_fuente_id_externo UNIQUE (fuente, id_externo)
);

CREATE TABLE usuario (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(255),
    correo   VARCHAR(255),
    password VARCHAR(255),
    CONSTRAINT uk_usuario_correo UNIQUE (correo)
);

-- Favoritos: relacion muchos a muchos entre usuario y concierto.
CREATE TABLE usuario_favoritos (
    usuario_id   BIGINT NOT NULL,
    favoritos_id BIGINT NOT NULL,
    CONSTRAINT fk_usuario_favoritos_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_usuario_favoritos_concierto
        FOREIGN KEY (favoritos_id) REFERENCES concierto (id)
);
